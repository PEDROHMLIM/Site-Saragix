/**
 * Traduz o país para o idioma ativo
 */
export function localizeCountry(country, lang = 'pt') {
  if (!country) return '';
  if (lang === 'pt') return country;
  const match = COUNTRY_NAMES[country];
  if (match && match[lang]) return match[lang];
  return country;
}

/**
 * Traduz a cidade / país do local (ex: "Reykjavik, Islândia")
 */
export function localizeSite(site, lang = 'pt') {
  if (!site) return '';
  if (lang === 'pt') return site;

  // Se tiver formato "Cidade, País"
  if (site.includes(', ')) {
    const parts = site.split(', ');
    const city = parts[0];
    const country = parts.slice(1).join(', ');
    const localizedCountry = localizeCountry(country, lang);
    return `${city}, ${localizedCountry}`;
  }

  return localizeCountry(site, lang);
}

/**
 * Traduz o nome da abertura
 */
export function localizeOpening(opening, lang = 'pt') {
  if (!opening) return '';
  if (lang === 'pt') return opening;

  // Busca exata
  if (OPENINGS_MAP[opening] && OPENINGS_MAP[opening][lang]) {
    return OPENINGS_MAP[opening][lang];
  }

  // Busca parcial por prefixo conhecido
  for (const [key, trans] of Object.entries(OPENINGS_MAP)) {
    if (opening.startsWith(key)) {
      const rest = opening.slice(key.length);
      return (trans[lang] || key) + rest;
    }
  }

  return opening;
}

/**
 * Traduz o ritmo de jogo (ex: Clássico -> Classic / Clásico)
 */
export function localizeSpeed(speed, lang = 'pt') {
  if (!speed) return '';
  if (speed === 'Clássico') {
    if (lang === 'en') return 'Classic';
    if (lang === 'es') return 'Clásico';
    return 'Clássico';
  }
  if (speed === 'Rápido') {
    if (lang === 'en') return 'Rapid';
    if (lang === 'es') return 'Rápido';
    return 'Rápido';
  }
  return speed;
}

/**
 * Traduz a frase de destaque / highlight
 */
export function localizeHighlight(dailyGame, lang = 'pt') {
  if (!dailyGame || !dailyGame.highlight) return '';
  if (lang === 'pt') return dailyGame.highlight;

  // Partidas famosas com tradução curada
  if (dailyGame.id && FAMOUS_HIGHLIGHTS[dailyGame.id] && FAMOUS_HIGHLIGHTS[dailyGame.id][lang]) {
    return FAMOUS_HIGHLIGHTS[dailyGame.id][lang];
  }

  // Padrão template: "Confronto de alto nível com {N} lances entre {W} e {B} ({Y})."
  const templateMatch = dailyGame.highlight.match(/Confronto de alto nível com (\d+) lances entre (.+) e (.+) \((\d+)\)\./);
  if (templateMatch) {
    const [, moves, white, black, year] = templateMatch;
    if (lang === 'en') {
      return `High-level match with ${moves} moves between ${white} and ${black} (${year}).`;
    }
    if (lang === 'es') {
      return `Enfrentamiento de alto nivel con ${moves} jugadas entre ${white} y ${black} (${year}).`;
    }
  }

  return dailyGame.highlight;
}

/**
 * Formata a data atual no formato local do idioma
 */
export function formatLocalizedDate(date = new Date(), lang = 'pt') {
  const locale = lang === 'en' ? 'en-US' : lang === 'es' ? 'es-ES' : 'pt-BR';
  return date.toLocaleDateString(locale, {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  });
}
